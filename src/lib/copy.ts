/** Заголовок блока, когда организатор его не задавал (title === undefined). */
export function defaultTitle(type: BlockType, eventType: EventType = "wedding", lang: Language = "ru"): string {
  return titleOverrides[lang][eventType]?.[type] ?? baseTitles[lang][type];
}

/** Все заголовки по умолчанию этого типа блока — на любом языке и для любого события. */
export function allDefaultTitles(type: BlockType): string[] {
  return (["ru", "ky"] as const).flatMap((lang) => [
    baseTitles[lang][type],
    ...Object.values(titleOverrides[lang]).flatMap((o) => (o?.[type] ? [o[type]] : [])),
  ]);
}

